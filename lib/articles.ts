import type { Comparison } from "@/data/comparisons";

/**
 * Build an Article-like schema block from a comparison.
 */
export function comparisonArticleSchema(comparison: Comparison) {
  return {
    "@type": "Article",
    headline: comparison.title,
    description: comparison.summary,
    about: comparison.relatedEntities.map(
      (entitySlug) =>
        `https://leadflowproteam.com/entities/${entitySlug}#entity`,
    ),
    mentions: comparison.relatedServices.map(
      (serviceSlug) =>
        `https://leadflowproteam.com/services/${serviceSlug}#service`,
    ),
  };
}

/**
 * Get a short, quotable answer for a comparison question.
 */
export function getComparisonAnswer(slug: string) {
  return (
    [
      {
        slug: "aeo-vs-geo",
        answer:
          "AEO makes your answers extractable by answer engines; GEO makes your business part of the answer generated by AI systems like ChatGPT and Gemini. Both depend on structured data and consistent entity information.",
      },
    ].find((item) => item.slug === slug)?.answer ?? null
  );
}
